let currentLang = localStorage.getItem('suite_lang') || 'tr';

function t(key) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.tr;
  return dict[key] || TRANSLATIONS.tr[key] || key;
}

function applyLanguage(lang) {
  if (!TRANSLATIONS[lang]) lang = 'tr';
  currentLang = lang;
  localStorage.setItem('suite_lang', lang);

  const dict = TRANSLATIONS[lang];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (el.tagName === 'INPUT' && (el.type === 'text' || el.type === 'email')) {
        el.placeholder = dict[key];
      } else {
        el.innerHTML = dict[key];
      }
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.placeholder = dict[key];
    }
  });

  const selectEl = document.getElementById('lang-switch');
  if (selectEl) selectEl.value = lang;

  // Re-render open cart or dynamic elements if needed
  if (typeof renderCartDrawer === 'function') {
    renderCartDrawer();
  }
}

document.addEventListener('DOMContentLoaded', () => {
  applyLanguage(currentLang);
});
